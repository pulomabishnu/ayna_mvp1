#!/usr/bin/env node
/**
 * Builds supabase/seed/free_product_vinted.sql from a TSV of Ameera's Vinted
 * listings (one row per listing) with the official product photo for each.
 *
 *   node scripts/vinted-seed.mjs <listings.tsv> [out.sql]
 *
 * TSV columns: listing_id brand name size category image_url product_url image_source notes
 * Rows with the same brand + name become one prize with several units.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const [, , input, out = 'supabase/seed/free_product_vinted.sql'] = process.argv;
if (!input) {
  console.error('usage: node scripts/vinted-seed.mjs <listings.tsv> [out.sql]');
  process.exit(1);
}

const lines = readFileSync(input, 'utf8').split(/\r?\n/).filter((l) => l.trim());
const header = lines.shift().split('\t');
const col = (name) => {
  const i = header.indexOf(name);
  if (i < 0) throw new Error(`missing column ${name}`);
  return i;
};
const C = Object.fromEntries(['listing_id', 'brand', 'name', 'size', 'category', 'image_url', 'product_url', 'image_source'].map((k) => [k, col(k)]));

const sql = (v) => (v == null || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const seen = new Set();
const rows = lines.map((l) => {
  const f = l.split('\t');
  const r = Object.fromEntries(Object.entries(C).map(([k, i]) => [k, (f[i] || '').trim()]));
  if (!/^\d+$/.test(r.listing_id)) throw new Error(`bad listing id: ${l}`);
  if (seen.has(r.listing_id)) throw new Error(`duplicate listing ${r.listing_id}`);
  seen.add(r.listing_id);
  if (!r.brand || !r.name) throw new Error(`missing brand/name for ${r.listing_id}`);
  if (r.image_url && !/^https:\/\//.test(r.image_url)) throw new Error(`image must be https: ${r.listing_id}`);
  if (r.product_url && !/^https:\/\//.test(r.product_url)) throw new Error(`link must be https: ${r.listing_id}`);
  return r;
});

const products = new Map();
for (const r of rows) {
  const key = `${r.brand.toLowerCase()}|${r.name.toLowerCase()}`;
  if (!products.has(key)) products.set(key, { ...r, listings: [] });
  products.get(key).listings.push(r.listing_id);
}
const fromVinted = rows.filter((r) => r.image_source === 'vinted').length;

const body = `-- Free product prizes from Ameera's Vinted shop (vinted.com/member/3199007819).
-- ${products.size} products, ${rows.length} units (one unit per Vinted listing).
-- Photos are the brand's or a retailer's product photo${fromVinted ? `, except ${fromVinted} that use the Vinted photo (no official one found)` : ''}.
-- Generated by scripts/vinted-seed.mjs. Reward-only items: no health or efficacy claims.
--
-- Run after supabase/migrations/20261021120000_vinted_pool_sync.sql.
-- Safe to re-run: listings already known keep their status and any claim; a
-- prize that already exists (same brand and name, ignoring punctuation) is
-- reused, so items that were also in the PR haul are not added twice.
-- Each prize's units then follow its listings: sold on Vinted = not winnable.

with items (listing_id, name, brand, size, category, image_url, product_url) as (
  values
${rows.map((r) => `  (${r.listing_id}::bigint, ${sql(r.name)}, ${sql(r.brand)}, ${sql(r.size)}, ${sql(r.category || 'skincare')}, ${sql(r.image_url)}, ${sql(r.product_url)})`).join(',\n')}
),
products as (
  select distinct on (lower(brand), lower(name)) name, brand, size, category, image_url, product_url
  from items order by lower(brand), lower(name), listing_id
)
insert into public.reward_products (campaign_id, name, brand, size, category, image_url, product_url, inventory_total)
select 'free-product-2026', p.name, p.brand, p.size, p.category, p.image_url, p.product_url, 0
from products p
where not exists (
  select 1 from public.reward_products rp
  where rp.campaign_id = 'free-product-2026' and rp.product_id is null
    and regexp_replace(lower(rp.brand), '[^a-z0-9]', '', 'g') = regexp_replace(lower(p.brand), '[^a-z0-9]', '', 'g')
    and regexp_replace(lower(rp.name), '[^a-z0-9]', '', 'g') = regexp_replace(lower(p.name), '[^a-z0-9]', '', 'g')
);

with items (listing_id, name, brand) as (
  values
${rows.map((r) => `  (${r.listing_id}::bigint, ${sql(r.name)}, ${sql(r.brand)})`).join(',\n')}
)
insert into public.reward_vinted_listings (listing_id, reward_product_id, title)
select i.listing_id, rp.id, i.brand || ' ' || i.name
from items i
join lateral (
  select id from public.reward_products rp
  where rp.campaign_id = 'free-product-2026' and rp.product_id is null
    and regexp_replace(lower(rp.brand), '[^a-z0-9]', '', 'g') = regexp_replace(lower(i.brand), '[^a-z0-9]', '', 'g')
    and regexp_replace(lower(rp.name), '[^a-z0-9]', '', 'g') = regexp_replace(lower(i.name), '[^a-z0-9]', '', 'g')
  order by rp.created_at limit 1
) rp on true
on conflict (listing_id) do nothing;

select public.campaign_vinted_recount('free-product-2026');

select count(distinct l.reward_product_id) as vinted_products, count(*) as listings,
       count(*) filter (where l.status = 'available' and l.claim_id is null) as winnable
from public.reward_vinted_listings l;
`;
writeFileSync(out, body);
console.log(`wrote ${out}: ${products.size} products, ${rows.length} listings (${fromVinted} Vinted photos)`);
