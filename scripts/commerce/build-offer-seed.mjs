#!/usr/bin/env node
/**
 * Generates supabase/seed/2026-10-15_commerce_offers.sql: one commerce_offers
 * row per place each live product can be bought, one commerce_variants row per
 * Ayna option, and one commerce_audit_log row per product, from the
 * 2026-10-15 catalog audit.
 *
 * Amazon offers carry ASINs and links only (never a price, never an image).
 * Brand/partner prices are included only where the audit verified them on the
 * merchant's own site (src/data/commerceVerifiedOffers.js).
 * Every insert is guarded by "product exists", and the file is re-runnable:
 * it replaces only rows it created (provider_metadata.seed = this file).
 *
 *   npx tsx scripts/commerce/build-offer-seed.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { applyCatalogCorrections } from '../../src/data/catalogCorrections.js';
import { COMMERCE_VERIFIED_OFFERS } from '../../src/data/commerceVerifiedOffers.js';
import { resolveBuyUrl, isAmazonUrl } from '../../src/utils/buyLink.js';
import { getAmazonAffiliateUrlForProduct } from '../../src/data/productAffiliateUrls.js';
import { findBrandPartner } from '../../src/data/brandPartners.js';
import { resolveCommerce } from '../../src/commerce/router.js';
import { providerForUrl, PROVIDERS } from '../../src/commerce/policy.js';
import { asinFromUrl } from '../../src/commerce/amazon.js';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const SEED = '2026-10-15_commerce_offers';
const live = JSON.parse(fs.readFileSync(path.join(root, 'docs/commerce/audit/live_catalog_commerce_fields_2026-10-15.json'), 'utf8'));
const audit = JSON.parse(fs.readFileSync(path.join(root, 'docs/commerce/audit/catalog_audit_rows.json'), 'utf8'));
const auditById = Object.fromEntries(audit.map((r) => [r.ayna_product_id, r]));

const q = (v) => (v === null || v === undefined || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const cents = (amount) => (Number.isFinite(Number(amount)) && Number(amount) > 0 ? Math.round(Number(amount) * 100) : null);
const host = (u) => { try { return new URL(u).hostname.replace(/^www\./, ''); } catch { return null; } };
const https = (u) => (typeof u === 'string' && /^https:\/\//.test(u) ? u : null);
const partnerSlug = (p) => {
  const partner = findBrandPartner(p);
  if (!partner) return null;
  return { BUNI: 'buni', SootheHer: 'sootheher', Neycher: 'neycher', 'Winx Health': 'winx', gina: 'gina', Elitone: 'elitone', Proov: 'proov', VIO2: 'vio2', 'My Pelvic Bra': 'my-pelvic-bra', 'Connect Pelvic Floor Fitness': 'connect-pff', LOLA: 'lola', 'LiM Method': 'lim-method', 'Rèsa': 'resa' }[partner.name] || null;
};

const out = [
  `-- GENERATED by scripts/commerce/build-offer-seed.mjs. Apply after commerce_engine.sql.`,
  `-- Re-runnable: deletes and re-creates only the rows this seed created.`,
  `begin;`,
  `delete from public.commerce_variants where provider_metadata->>'seed' = '${SEED}';`,
  `delete from public.commerce_offers where provider_metadata->>'seed' = '${SEED}';`,
  `delete from public.commerce_audit_log where check_source = 'catalog_audit_2026-10-15';`,
];
let offers = 0;
let variants = 0;

for (const raw of live.products) {
  const p = applyCatalogCorrections(raw);
  const primary = resolveCommerce(p, null);
  const verified = COMMERCE_VERIFIED_OFFERS[p.id] || null;
  const a = auditById[p.id] || {};
  const partner = partnerSlug(p);
  const list = [];

  // Primary offer = what the Buy button opens today (no size chosen).
  if (primary?.destinationUrl) list.push({ url: primary.destinationUrl, primary: true });
  // Alternatives: the exact brand page when Amazon is primary, Amazon when it isn't.
  const brandAlt = resolveBuyUrl(p, null, { amazonAllowed: false });
  if (brandAlt && !list.some((o) => o.url === brandAlt)) list.push({ url: brandAlt, primary: false });
  const amazonAlt = !partner && (getAmazonAffiliateUrlForProduct(p) || (isAmazonUrl(p.affiliateUrl) ? p.affiliateUrl : null));
  if (amazonAlt && !list.some((o) => isAmazonUrl(o.url))) list.push({ url: amazonAlt, primary: false });

  for (const o of list) {
    const isAmazon = isAmazonUrl(o.url);
    let provider = providerForUrl(o.url);
    if (p.type === 'digital' && !isAmazon) provider = PROVIDERS.APP_OR_SERVICE;
    if (partner && provider === PROVIDERS.BRAND_DIRECT && /[?&](ref|af|sca_ref|bg_ref|dt_id)=/i.test(o.url)) provider = PROVIDERS.BRAND_AFFILIATE;
    const method = p.type === 'digital' && !isAmazon ? 'external_service'
      : [PROVIDERS.AMAZON_ASSOCIATES, PROVIDERS.SHOPMY, PROVIDERS.SHOPIFY_COLLABS, PROVIDERS.IMPACT, PROVIDERS.BRAND_AFFILIATE].includes(provider) ? 'affiliate_redirect' : 'external_redirect';
    const useVerified = !isAmazon && verified && (verified.hosts || []).includes(host(o.url)) ? verified : null;
    const price = useVerified?.price || null;
    const metadata = { seed: SEED, merchantTitle: useVerified?.merchantTitle || null };
    offers += 1;
    const offerId = `(select id from public.commerce_offers where provider_metadata->>'seed' = '${SEED}' and product_id = ${q(p.id)} and destination_url = ${q(https(o.url))} limit 1)`;
    out.push(`insert into public.commerce_offers(product_id, provider, commerce_method, payment_provider, merchant_name, merchant_domain, destination_url, canonical_url, asin, currency, regular_price_cents, sale_price_cents, current_price_cents, price_source, price_verified_at, availability, affiliate_redirect, partner_id, is_primary, selection_reason, verification_method, confidence, audit_status, audit_notes, requires_manual_review, provider_metadata)
select ${q(p.id)}, ${q(provider)}, ${q(method)}, 'external_merchant', ${q(isAmazon ? 'Amazon' : (useVerified?.merchant || p.brand || host(o.url)))}, ${q(host(o.url))}, ${q(https(o.url))}, ${q(isAmazon ? null : https(o.url))}, ${q(isAmazon ? asinFromUrl(o.url) : null)},
  ${q(price ? price.currency : null)}, ${price ? (cents(price.regular) ?? cents(price.amount)) : 'null'}, ${price && price.regular && price.regular > price.amount ? cents(price.amount) : 'null'}, ${price ? cents(price.amount) : 'null'}, ${q(price ? price.source : (isAmazon ? 'unknown' : 'legacy_import'))}, ${q(price ? price.verifiedAt : null)},
  ${q(isAmazon ? 'UNKNOWN' : (useVerified?.availability || 'UNKNOWN'))}, ${method === 'affiliate_redirect'}, ${q(partner)}, ${o.primary}, ${q(o.primary ? primary.selectionReason : 'ALTERNATIVE_OFFER')},
  ${q(isAmazon ? 'asin_extracted_only' : (useVerified?.verificationMethod || 'unable_to_verify'))}, ${q(isAmazon ? 'manual_review_required' : (a.confidence || null))}, ${q(o.primary ? a.audit_status : null)}, ${q(o.primary ? a.notes : null)}, ${isAmazon || !useVerified || a.manual_review_required === 'yes'}, ${q(JSON.stringify(metadata))}::jsonb
where exists (select 1 from public.product_catalog where id = ${q(p.id)});`);

    // Variants that belong to this offer: Amazon offers get options with a child ASIN; brand offers get options on the same host.
    for (const v of p.variants || []) {
      const vRouted = resolveCommerce(p, v);
      const vAsin = v.amazonAsin ? String(v.amazonAsin).toUpperCase() : null;
      const belongs = isAmazon ? Boolean(vAsin) : Boolean(v.url) && host(v.url) === host(o.url);
      if (!belongs) continue;
      const facts = !isAmazon && useVerified ? useVerified.variants?.[v.id] : null;
      variants += 1;
      out.push(`insert into public.commerce_variants(offer_id, product_id, ayna_variant_id, provider_variant_id, asin, sku, upc, variant_title, currency, current_price_cents, price_source, price_verified_at, availability, canonical_url, destination_url, provider_metadata)
select ${offerId}, ${q(p.id)}, ${q(v.id)}, ${q(isAmazon ? null : v.id)}, ${q(isAmazon ? vAsin : null)}, ${q(facts?.sku)}, ${q(facts?.barcode)}, ${q(v.label)},
  ${q(facts?.price ? facts.price.currency : null)}, ${facts?.price ? cents(facts.price.amount) : 'null'}, ${q(facts?.price ? facts.price.source : 'unknown')}, ${q(facts?.price ? facts.price.verifiedAt : null)},
  ${q(facts && typeof facts.available === 'boolean' ? (facts.available ? 'AVAILABLE' : 'OUT_OF_STOCK') : 'UNKNOWN')}, ${q(isAmazon ? null : https(v.url))}, ${q(https(isAmazon ? vRouted.destinationUrl : v.url))}, ${q(JSON.stringify({ seed: SEED }))}::jsonb
where exists (select 1 from public.product_catalog where id = ${q(p.id)}) and ${offerId} is not null;`);
    }
  }

  out.push(`insert into public.commerce_audit_log(product_id, provider, new_status, issues, severity, price_changed, check_source, automatic, notes)
select ${q(p.id)}, ${q(primary?.provider || null)}, ${q(a.audit_status || 'UNVERIFIED')}, ${q(`{${(a.issue_types || '').split(';').filter(Boolean).map((s) => `"${s.trim()}"`).join(',')}}`)}::text[], ${q(a.severity || null)}, ${a.price_mismatch === 'yes' ? 'true' : 'null'}, 'catalog_audit_2026-10-15', true, ${q(a.notes || null)}
where exists (select 1 from public.product_catalog where id = ${q(p.id)});`);
}
out.push('commit;', '');
const target = path.join(root, `supabase/seed/${SEED}.sql`);
fs.writeFileSync(target, out.join('\n'));
console.log(`wrote ${path.relative(root, target)}: ${offers} offers, ${variants} variants`);
