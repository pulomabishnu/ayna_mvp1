// Builds docs/commerce/AMAZON_SIZED_AND_SERVICES.md from the audit JSON.
// Run: node scripts/commerce/build-sized-and-services-report.mjs
import fs from 'node:fs';

const read = (p) => JSON.parse(fs.readFileSync(new URL(`../../docs/commerce/audit/${p}`, import.meta.url), 'utf8'));
const sized = read('amazon_sized_products.json');
const auditRows = read('catalog_audit_rows.json');
const rows = auditRows.rows || auditRows;

const esc = (s) => String(s ?? '').replace(/\|/g, '/').replace(/\n/g, ' ');
const host = (u) => { try { return new URL(u).hostname.replace(/^www\./, ''); } catch { return ''; } };
const out = [];

out.push('# Amazon sized products and apps/services (2026-10-15)', '');
out.push('Generated by `scripts/commerce/build-sized-and-services-report.mjs` from `docs/commerce/audit/`. Nothing here is verified on Amazon yet; every row still needs the human check.', '');

function productTable(p) {
  const asins = p.options.map((o) => o.childAsin).filter(Boolean);
  const dupes = asins.filter((a, i) => asins.indexOf(a) !== i);
  const missing = p.options.filter((o) => !o.childAsin).length;
  const urls = new Set(p.options.map((o) => o.routesTo || ''));
  out.push(`### ${esc(p.name)} (\`${p.id}\`)`, '');
  out.push(`- Listing ASIN \`${p.listingAsin || 'none'}\`${p.listingAsin && !p.listingIsOneOfChildren ? ' — **not any of the size ASINs, check it**' : ''}`);
  out.push(`- Every Ayna size has a child ASIN: ${missing ? `**no, ${missing} missing**` : 'yes'}`);
  out.push(`- Child ASIN shared by two sizes: ${dupes.length ? `**yes: ${[...new Set(dupes)].join(', ')}**` : 'no'}`);
  out.push(`- Link changes when the size changes: ${urls.size === p.options.length ? 'yes, every size has its own link' : `**no, ${p.options.length} sizes share ${urls.size} links**`}`, '');
  out.push('| Ayna size | Child ASIN | Buy button opens | Route |', '| --- | --- | --- | --- |');
  for (const o of p.options) out.push(`| ${esc(o.label)} | ${o.childAsin || '—'} | ${o.routesTo ? `${host(o.routesTo)}${o.childAsin ? ` /dp/${o.childAsin}` : ''}` : 'nothing'} | ${o.reason} |`);
  out.push('');
}

out.push(`## The ${sized.child_asin_for_every_size.length} products with a child ASIN for every size`, '');
out.push('The strongest Amazon mappings. Once a person confirms them, they are the model for how sizes map to Amazon.', '');
sized.child_asin_for_every_size.forEach(productTable);

const notExact = [...sized.child_asin_for_some_sizes, ...sized.sizes_but_one_generic_listing];
out.push(`## The ${notExact.length} products that stay AMAZON_VARIANT_NOT_EXACT`, '');
out.push('Sizes with their own child ASIN go to Amazon; the rest go to that exact size on the brand site, or nowhere if there is none.', '');
notExact.forEach(productTable);

const services = rows.filter((x) => x.type === 'digital' || /^app_or_service/.test(x.selected_primary_offer));
out.push(`## Apps and services (${services.length})`, '');
out.push('Amazon logic doesn\'t apply except to the two physical devices listed as digital (Oura, Inito). Method is `external_service`.', '');
out.push('| Product | Opens | Tracking | Ayna price text | Found on official site | Status |', '| --- | --- | --- | --- | --- | --- |');
for (const x of services) {
  out.push(`| ${esc(x.product_name)} | ${x.commerce_url ? host(x.commerce_url) : '**no link**'} | ${x.affiliate_route === 'none' ? 'none' : esc(x.affiliate_route)} | ${esc(x.ayna_current_price)} | ${esc(x.verified_source_price) || '—'} | ${x.audit_status}${x.mismatch_reason ? ` (${x.mismatch_reason})` : ''} |`);
}
out.push('');

fs.writeFileSync(new URL('../../docs/commerce/AMAZON_SIZED_AND_SERVICES.md', import.meta.url), `${out.join('\n')}\n`);
console.log('wrote docs/commerce/AMAZON_SIZED_AND_SERVICES.md');
