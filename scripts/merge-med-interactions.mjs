// Merges the medication-interaction research (med_interactions.json) into
// src/data/matching/medInteractions.research.js, read by src/matching/medications.js.
// Drops info-only rows (a drug lowering a nutrient is not a reason to avoid the
// product) and rows without a credible source. Usage: node scripts/merge-med-interactions.mjs <file>
import fs from 'node:fs';
// Founder rule (Oct 24 2026): clinical claims cite reputable .gov health sites only
// (MedlinePlus, NIH and its institutes incl. NLM, FDA, CDC, womenshealth.gov, AHRQ).
// PubMed/PMC papers are left out until someone has opened and checked them.
const ALLOW = /(^|\.)(nih\.gov|medlineplus\.gov|fda\.gov|cdc\.gov|womenshealth\.gov|ahrq\.gov|hhs\.gov)$/i;
const PAPER = /^(pubmed|pmc)\.ncbi\.nlm\.nih\.gov$/i;
const credible = (u) => { try { const h = new URL(u).hostname; return ALLOW.test(h) && !PAPER.test(h); } catch { return false; } };
const data = JSON.parse(fs.readFileSync(process.argv[2], 'utf8')).interactions || [];
// Words that would match the wrong thing in product text.
const UNSAFE_TERMS = new Set(['fiber', 'dietary fiber', 'bha', 'sulfur', 'potassium', 'soy', 'soybean', 'b12', 'vitamin h', 'coffee extract', 'panax', 'aspirin']);
const rows = [];
const keywords = {};
const meds = new Map();
for (const r of data) {
  if (!r?.medication_class || !r.ingredient_key || r.ingredient_key === 'any' || r.kind === 'depletion') continue;
  if (!['avoid', 'caution'].includes(r.verdict) || !credible(r.source_url)) continue;
  if (/—/.test(r.message)) continue;
  rows.push({ medication_class: r.medication_class, product_ingredient: r.ingredient_key, verdict: r.verdict, kind: r.kind || null, message: r.message, source: r.source_url, reviewed_on: '2026-10-17', reviewer: 'research', needs_clinical_review: true });
  const terms = (r.ingredient_terms || []).map((t) => String(t).toLowerCase()).filter((t) => t.length >= 4 && !UNSAFE_TERMS.has(t));
  keywords[r.ingredient_key] = [...new Set([...(keywords[r.ingredient_key] || []), ...terms])];
  if (!meds.has(r.medication_class)) meds.set(r.medication_class, { generics: new Set(), brands: new Set() });
  (r.medications || []).forEach((m) => meds.get(r.medication_class).generics.add(String(m).toLowerCase()));
  (r.brands || []).forEach((b) => meds.get(r.medication_class).brands.add(String(b)));
}
const medList = [...meds.entries()].map(([cls, v]) => ({ class: cls, generics: [...v.generics], brands: [...v.brands] }));
const out = `// Generated by scripts/merge-med-interactions.mjs from the medication research (Oct 17). Do not edit by hand.
export const RESEARCH_INTERACTIONS = ${JSON.stringify(rows, null, 1)};
export const RESEARCH_INGREDIENT_KEYWORDS = ${JSON.stringify(keywords, null, 1)};
export const RESEARCH_MEDICATIONS = ${JSON.stringify(medList, null, 1)};
`;
fs.writeFileSync(new URL('../src/data/matching/medInteractions.research.js', import.meta.url), out);
console.log(`interactions: ${rows.length}, ingredient keys: ${Object.keys(keywords).length}, classes: ${medList.length}`);
