// Appends reviewed product x need rows to the research link table
// (src/data/matching/needMap.research.json and .js, kept identical).
//   node scripts/apply-link-review.mjs review0.json review1.json ... [--added gaps_review.json]
// Review rows grade or remove links the engine already makes. Rows from
// --added files create links the rules missed (added: true).
// Every row is validated: known product, known need, allowed strength/grade,
// and a source that passes src/data/sourcePolicy.js.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { isCredibleScienceSource } from '../src/data/sourcePolicy.js';
import { CATALOG_PRODUCTS } from '../src/data/products.js';
import { NEED_BY_ID } from '../src/matching/ontology.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const addedFiles = [];
const reviewFiles = [];
for (let i = 0; i < args.length; i++) { if (args[i] === '--added') addedFiles.push(args[++i]); else reviewFiles.push(args[i]); }

const products = new Set(CATALOG_PRODUCTS.map((p) => p.id));
const STRENGTH = new Set(['primary', 'secondary', 'none']);
const GRADE = new Set(['A', 'B', 'C']);
const today = new Date().toISOString().slice(0, 10);
const plain = (t) => String(t || '').replace(/\s*[—–]\s*/g, ', ').replace(/\s+/g, ' ').trim().slice(0, 300);

const jsonPath = path.join(root, 'src/data/matching/needMap.research.json');
const jsPath = path.join(root, 'src/data/matching/needMap.research.js');
const table = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
const index = new Map(table.map((r, i) => [`${r.product}|${r.need}`, i]));
const report = { added: 0, updated: 0, rejected: [] };

function take(r, added) {
  const why = [];
  if (!products.has(r.product)) why.push('unknown product');
  if (!NEED_BY_ID[r.need]) why.push('unknown need');
  if (!STRENGTH.has(r.strength)) why.push('bad strength');
  if (!GRADE.has(r.grade)) why.push('bad grade');
  if (!isCredibleScienceSource(r.source_url)) why.push(`source fails policy (${r.source_url})`);
  if (added && r.strength === 'none') why.push('added row cannot be none');
  if (why.length) { report.rejected.push(`${r.product}|${r.need}: ${why.join(', ')}`); return; }
  const row = { product: r.product, need: r.need, strength: r.strength, grade: r.grade, rationale: plain(r.rationale), source_url: r.source_url, reviewer: 'research-audit', reviewed: today, ...(added ? { added: true } : {}) };
  const k = `${r.product}|${r.need}`;
  if (index.has(k)) { table[index.get(k)] = row; report.updated++; } else { index.set(k, table.length); table.push(row); report.added++; }
}

for (const f of reviewFiles) for (const r of JSON.parse(fs.readFileSync(f, 'utf8'))) take(r, false);
for (const f of addedFiles) for (const r of JSON.parse(fs.readFileSync(f, 'utf8')).added || []) take(r, true);

fs.writeFileSync(jsonPath, `${JSON.stringify(table, null, 1)}\n`);
fs.writeFileSync(jsPath, `// Generated by scripts/merge-research.mjs and scripts/apply-link-review.mjs. Do not edit by hand.\nexport default ${JSON.stringify(table, null, 1)};\n`);
console.log(JSON.stringify(report, null, 1));
