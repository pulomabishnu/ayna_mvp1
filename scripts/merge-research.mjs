// Merges the evidence research (one JSON file per health domain, written by the
// research pass) into the files the matching engine reads:
//   src/data/matching/needMap.research.json   product x need: strength + grade + source
//   src/data/matching/safety.research.json    pregnancy / breastfeeding status + source
//   src/data/matching/needs.research.json     per-need summary, what works, cautions, red flags, gaps
// Only rows whose source is on the credible-source allowlist are kept.
// Usage: node scripts/merge-research.mjs <dir with out_*.json>
import fs from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
if (!dir) { console.error('usage: node scripts/merge-research.mjs <dir>'); process.exit(1); }
// Founder rule (Oct 24 2026): clinical claims cite reputable .gov health sites only
// (MedlinePlus, NIH and its institutes incl. NLM, FDA, CDC, womenshealth.gov, AHRQ).
// PubMed/PMC papers are left out until someone has opened and checked them.
const ALLOW = /(^|\.)(nih\.gov|medlineplus\.gov|fda\.gov|cdc\.gov|womenshealth\.gov|ahrq\.gov|hhs\.gov)$/i;
const PAPER = /^(pubmed|pmc)\.ncbi\.nlm\.nih\.gov$/i;
const credible = (u) => { try { const h = new URL(u).hostname; return ALLOW.test(h) && !PAPER.test(h); } catch { return false; } };
const STRENGTH = new Set(['primary', 'secondary', 'none']);
const GRADE = new Set(['A', 'B', 'C']);
const STATUS = new Set(['ok', 'avoid', 'ask_clinician', 'unknown']);
const today = new Date().toISOString().slice(0, 10);

const rows = new Map();
const safety = new Map();
const needs = [];
const redFlags = [];
const dropped = [];
for (const f of fs.readdirSync(dir).filter((x) => /^out_.*\.json$/.test(x)).sort()) {
  const data = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  for (const r of data.rows || []) {
    if (!r?.product || !r?.need || !STRENGTH.has(r.strength) || !GRADE.has(r.grade)) { dropped.push(`${f}: bad row ${JSON.stringify(r).slice(0, 80)}`); continue; }
    // A row the researcher could not verify (placeholder source) is not evidence: the draft grade stays.
    if (/evidence unverified|unverified/i.test(String(r.rationale || ''))) { dropped.push(`${f}: ${r.product}|${r.need} unverified, kept draft`); continue; }
    if (!credible(r.source_url)) { dropped.push(`${f}: ${r.product}|${r.need} source not on allowlist (${r.source_url})`); continue; }
    rows.set(`${r.product}|${r.need}`, { product: r.product, need: r.need, strength: r.strength, grade: r.grade, rationale: String(r.rationale || '').slice(0, 300), source_url: r.source_url, reviewer: 'research', reviewed: today });
  }
  for (const s of data.safety || []) {
    if (!s?.product || !STATUS.has(s.pregnancy) || !STATUS.has(s.breastfeeding)) continue;
    if (!credible(s.source_url)) { dropped.push(`${f}: safety ${s.product} source not on allowlist`); continue; }
    const prev = safety.get(s.product);
    // Two domains disagree: keep the more cautious answer. "unknown" means no
    // information, so it never replaces a sourced answer.
    const rank = { avoid: 3, ask_clinician: 2, ok: 1, unknown: 0 };
    const pick = (a, b) => (!a ? b : rank[a] >= rank[b] ? a : b);
    const preg = pick(prev?.pregnancy, s.pregnancy);
    const bf = pick(prev?.breastfeeding, s.breastfeeding);
    safety.set(s.product, { product: s.product, pregnancy: preg, breastfeeding: bf,
      pregnancy_source: preg === s.pregnancy && s.pregnancy !== 'unknown' ? s.source_url : prev?.pregnancy_source || null,
      breastfeeding_source: bf === s.breastfeeding && s.breastfeeding !== 'unknown' ? s.source_url : prev?.breastfeeding_source || null,
      source_url: s.source_url, reviewed: today });
  }
  for (const r of data.red_flags || []) if (r?.id && credible(r.source_url)) redFlags.push(r);
  for (const n of data.needs || []) {
    needs.push({ ...n, effective_types: (n.effective_types || []).map((t) => ({ ...t, sources: (t.sources || []).filter(credible) })) });
  }
}
const out = (name, v) => fs.writeFileSync(new URL(`../src/data/matching/${name}`, import.meta.url), `${JSON.stringify(v, null, 1)}\n`);
// The engine imports a .js module (plain Node, which Vercel's API functions use, can't import JSON without an attribute).
const outJs = (name, v) => fs.writeFileSync(new URL(`../src/data/matching/${name}`, import.meta.url), `// Generated by scripts/merge-research.mjs. Do not edit by hand.\nexport default ${JSON.stringify(v, null, 1)};\n`);
outJs('needMap.research.js', [...rows.values()]);
out('needMap.research.json', [...rows.values()]);
outJs('safety.research.js', [...safety.values()]);
out('safety.research.json', [...safety.values()]);
out('needs.research.json', needs);
out('redFlags.research.json', redFlags);
const g = [...rows.values()].reduce((a, r) => { a[r.strength === 'none' ? 'none' : r.grade] = (a[r.strength === 'none' ? 'none' : r.grade] || 0) + 1; return a; }, {});
console.log(`research rows: ${rows.size} ${JSON.stringify(g)}; safety: ${safety.size}; needs: ${needs.length}; dropped: ${dropped.length}`);
if (dropped.length) console.log(dropped.slice(0, 40).join('\n'));
