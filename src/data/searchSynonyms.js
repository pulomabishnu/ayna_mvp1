/** Every canonical term the engine should prefer when correcting. */
export function curatedCanonicalTerms() {
  const out = new Set(Object.keys(MISSPELLINGS));
  for (const v of Object.values(PHRASE_JOINS)) v.split(/\s+/).forEach((w) => out.add(w));
  for (const k of Object.keys(TERM_NEEDS)) k.split(/\s+/).forEach((w) => out.add(w));
  for (const k of Object.keys(CATEGORY_TERMS)) k.split(/\s+/).forEach((w) => out.add(w));
  return [...out].filter((w) => w.length > 1);
}
