// Search vocabulary for every symptom, diagnosis and allergy search bar
// (quiz, shop search, community and library search).
//
// Each term is something a person might type or pick, mapped to the
// existing need / condition / allergen ids the match engine already scores.
// A term can name more than one need ("itchy discharge" = irritation +
// discharge), which makes the match more specific than one broad option.
//
// Rules (same as ontology.js):
//   - A symptom term maps to SYMPTOM needs only. It never infers a cause,
//     a diagnosis or a life stage (period pain never means endometriosis).
//   - Condition terms only map to a condition when the person names it.
//   - care: 'check' marks symptoms that MedlinePlus / ACOG say to get
//     checked (bleeding after menopause or after sex, blood in urine, a
//     breast lump, fever with pelvic pain). Picking one raises a care note;
//     it never blocks or diagnoses.

